<?php

namespace App\Service;

use App\Models\CourtPricingRule;
use App\Models\CourtScheduleConfig;
use App\Repository\CourtReservationRepository;
use Illuminate\Database\QueryException;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Str;
use Symfony\Component\HttpFoundation\Response;

class CourtReservationService extends BaseService
{
    public function __construct(
        protected CourtReservationRepository $courtReservationRepository,
        protected CourtAuthorizationService $courtAuthorizationService,
    ) {
    }

    /**
     * One day's slots (free/reserved) with member-visible reservation data and a
     * resolved default price for each free slot.
     */
    public function day(int $courtId, string $date): array
    {
        $this->courtAuthorizationService->assertCanManageReservations($courtId, Auth::id());

        $weekday = Carbon::parse($date)->dayOfWeek; // 0 = Sunday .. 6 = Saturday

        $config = $this->scheduleConfigFor($courtId, $weekday);
        $slots = SlotService::generateSlots($config);

        $rules = CourtPricingRule::query()
            ->where('court_id', $courtId)
            ->where('weekday', $weekday)
            ->get(['id', 'start_time', 'end_time', 'price_cents']);

        $reservations = $this->courtReservationRepository
            ->reservationsForDay($courtId, $date)
            ->keyBy(fn ($reservation) => substr($reservation->start_time, 0, 5));

        $slotPayload = [];
        foreach ($slots as $slot) {
            $startHm = substr($slot['start_time'], 0, 5);
            $endHm = substr($slot['end_time'], 0, 5);

            $reservation = $reservations->get($startHm);

            if ($reservation !== null) {
                $slotPayload[] = [
                    'start_time' => $startHm,
                    'end_time' => $endHm,
                    'status' => 'reserved',
                    'reservation' => [
                        'id' => $reservation->id,
                        'customer_name' => $reservation->customer_name,
                        'description' => $reservation->description,
                        'price_cents' => (int) $reservation->price_cents,
                        'is_mensalista' => (bool) $reservation->is_mensalista,
                        'recurrence_group_id' => $reservation->recurrence_group_id,
                        'created_by' => $reservation->created_by,
                    ],
                ];

                continue;
            }

            $slotPayload[] = [
                'start_time' => $startHm,
                'end_time' => $endHm,
                'status' => 'free',
                'default_price_cents' => SlotService::resolvePriceCents(
                    $rules,
                    $slot['start_time'],
                    $slot['end_time']
                ),
            ];
        }

        return [
            'date' => $date,
            'weekday' => $weekday,
            'slots' => $slotPayload,
        ];
    }

    /**
     * Month markers: days with >=1 reservation + a count, keyed YYYY-MM-DD.
     */
    public function agenda(int $courtId, string $month): array
    {
        $this->courtAuthorizationService->assertCanManageReservations($courtId, Auth::id());

        $monthStart = Carbon::createFromFormat('Y-m', $month)->startOfMonth();
        $monthEnd = (clone $monthStart)->endOfMonth();

        return [
            'days' => $this->courtReservationRepository->countByDay(
                $courtId,
                $monthStart->format('Y-m-d'),
                $monthEnd->format('Y-m-d')
            ),
        ];
    }

    /**
     * Create a reservation (one-off or mensalista). Returns created_count and
     * the skipped_dates reported from mensalista expansion.
     */
    public function reserve(array $validated, int $courtId): array
    {
        $this->courtAuthorizationService->assertCanManageReservations($courtId, Auth::id());

        // Widen the validated HH:MM pair to HH:MM:SS HERE (design A1 Option A), so
        // the slot-membership re-check and the unique index all operate on uniform
        // HH:MM:SS generated by phase 2 itself.
        $start = $validated['startTime'] . ':00';
        $end = $validated['endTime'] . ':00';
        $date = $validated['reservationDate'];
        $priceCents = (int) $validated['priceCents'];
        $isMensalista = (bool) ($validated['isMensalista'] ?? false);

        $this->assertSlotOnGrid($courtId, $date, $start, $end);

        $recurrenceGroupId = $isMensalista ? (string) Str::uuid() : null;

        $base = [
            'court_id' => $courtId,
            'start_time' => $start,
            'end_time' => $end,
            'price_cents' => $priceCents,
            'customer_name' => $validated['customerName'],
            'description' => $validated['description'] ?? null,
            'is_mensalista' => $isMensalista,
            'recurrence_group_id' => $recurrenceGroupId,
            'created_by' => Auth::id(),
        ];

        $skipped = [];

        $createdCount = DB::transaction(function () use ($base, $date, $courtId, $start, $isMensalista, &$skipped) {
            // Anchor first. A collision on the anchor is fatal (operator picked it
            // from a "free" cell, so a 409 means a race).
            if ($this->courtReservationRepository->slotTaken($courtId, $date, $start)) {
                throw new \Exception(
                    __('error.court_reservation.slot_taken'),
                    Response::HTTP_CONFLICT
                );
            }

            try {
                $this->courtReservationRepository->insert(array_merge($base, [
                    'reservation_date' => $date,
                ]));
            } catch (QueryException $e) {
                if ($e->getCode() === '23000') {
                    Log::warning('court reservation anchor race', [
                        'court_id' => $courtId,
                        'reservation_date' => $date,
                        'start_time' => $start,
                    ]);

                    throw new \Exception(
                        __('error.court_reservation.slot_taken'),
                        Response::HTTP_CONFLICT
                    );
                }

                throw $e;
            }

            $count = 1;

            if (!$isMensalista) {
                return $count;
            }

            foreach ($this->mensalistaDates($date) as $replicaDate) {
                // Each replica insert is INDEPENDENTLY guarded in its OWN try/catch
                // inside the closure. A caught 23000 is swallowed into $skipped and
                // NEVER rethrown out of the closure — SQLite/MySQL both roll back only
                // the failing statement, so committed rows survive (design §4).
                try {
                    $this->courtReservationRepository->insert(array_merge($base, [
                        'reservation_date' => $replicaDate,
                    ]));
                    $count++;
                } catch (QueryException $e) {
                    if ($e->getCode() === '23000') {
                        $skipped[] = $replicaDate;
                        Log::warning('court reservation replica skipped (occupied)', [
                            'court_id' => $courtId,
                            'reservation_date' => $replicaDate,
                            'start_time' => $start,
                        ]);

                        continue;
                    }

                    throw $e;
                }
            }

            return $count;
        });

        return [
            'created_count' => $createdCount,
            'skipped_dates' => $skipped,
        ];
    }

    /**
     * Cancel one reservation or (scope=future) the clicked occurrence and all
     * later ones in its recurrence group. Hard-deletes (design §1/§7).
     */
    public function cancel(int $courtId, int $reservationId, string $scope): array
    {
        $this->courtAuthorizationService->assertCanManageReservations($courtId, Auth::id());

        $reservation = $this->courtReservationRepository->firstScoped($courtId, $reservationId);

        throw_if(!$reservation, new \Exception(
            __('error.court_reservation.not_found'),
            Response::HTTP_NOT_FOUND
        ));

        $deleted = $this->courtReservationRepository->deleteGroupOrOne($reservation, $scope);

        return ['deleted_count' => $deleted];
    }

    /**
     * Later same-weekday dates in the SAME calendar month as the anchor.
     *
     * @return array<int, string> list of Y-m-d strings
     */
    private function mensalistaDates(string $anchorDate): array
    {
        $anchor = Carbon::parse($anchorDate);
        $anchorMonth = $anchor->month;

        $dates = [];
        $cursor = (clone $anchor)->addDays(7);

        while ($cursor->month === $anchorMonth) {
            $dates[] = $cursor->format('Y-m-d');
            $cursor->addDays(7);
        }

        return $dates;
    }

    private function assertSlotOnGrid(int $courtId, string $date, string $start, string $end): void
    {
        $weekday = Carbon::parse($date)->dayOfWeek;
        $config = $this->scheduleConfigFor($courtId, $weekday);
        $slots = SlotService::generateSlots($config);

        foreach ($slots as $slot) {
            if ($slot['start_time'] === $start && $slot['end_time'] === $end) {
                return;
            }
        }

        throw new \Exception(
            __('error.court_reservation.invalid_slot'),
            Response::HTTP_UNPROCESSABLE_ENTITY
        );
    }

    /**
     * Load the weekday's schedule config via Eloquent (soft-delete-aware; never
     * DB::table) so a soft-deleted config does not generate phantom slots.
     */
    private function scheduleConfigFor(int $courtId, int $weekday): ?CourtScheduleConfig
    {
        return CourtScheduleConfig::query()
            ->where('court_id', $courtId)
            ->where('weekday', $weekday)
            ->first();
    }
}
